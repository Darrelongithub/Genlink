def _guest(client, name: str) -> dict:
    body = client.post("/api/v1/students", json={"display_name": name, "as_guest": True}).json()
    return {"student_id": body["student_id"], "headers": {"x-csrf-token": body["csrf_token"]}}


def test_cohort_fitting_writes_the_global_row_and_a_topic_row_when_earned(client, services, make_answer):
    """``params_for`` reads a topic row before the global one, and nothing wrote one.

    ``train_params`` only ever wrote ``(scope, "*")``, so the per-topic branch was
    dead code. Fitting the topic is the whole point of the branch: guess and slip
    differ by skill, and one cohort average is an average over the entire bank.
    """
    from adapt.db.models import BktParams

    # The test client keeps one cookie jar, so each learner must be created and
    # used before the next one signs in -- a stale header would be a CSRF refusal,
    # not a data bug.
    picker = _guest(client, "Picker")
    picked = client.get("/api/v1/practice?count=1", headers=picker["headers"]).json()["items"][0]
    item_id, topic_id = picked["item"]["id"], picked["topic_id"]

    learners = []
    for i in range(3):
        person = _guest(client, f"Fit {i}")
        learners.append(person)
        session = client.post(
            "/api/v1/sessions", json={"mode": "practice"}, headers=person["headers"]
        ).json()["session_id"]
        for attempt_no, correct in ((1, True), (2, False)):
            response = client.post(
                "/api/v1/attempts",
                json={
                    "session_id": session,
                    "item_id": item_id,
                    "answer": make_answer(item_id, correct=correct),
                    "attempt_no": attempt_no,
                },
                headers=person["headers"],
            )
            assert response.status_code == 200, response.text

    diag = services.ai1.train_params(min_learners=3, min_sequences_per_topic=2)
    assert diag.get("skipped") is None, diag
    assert topic_id in diag.get("topics_fitted", []), diag

    with services.scope() as s:
        global_row = s.get(BktParams, ("global", "*"))
        topic_row = s.get(BktParams, ("global", topic_id))
        assert global_row is not None and global_row.n_sequences >= 3, global_row
        assert topic_row is not None and topic_row.n_sequences >= 2, topic_row
        # The read path has to prefer the topic row -- otherwise the fit is written
        # and never used, which is the bug this test exists for.
        params = services.ai1.params_for(learners[0]["student_id"], topic_id, s)
        assert abs(params.p_learn - float(topic_row.p_learn)) < 1e-9, (params.p_learn, topic_row.p_learn)

        # And a learner who answered *before* the fit is not frozen on the priors:
        # the fitted parameters are the filter's, the belief is theirs.
        from adapt.db.models import BktState

        state = s.get(BktState, (learners[0]["student_id"], topic_id))
        assert state is not None
        assert abs(float(state.p_learn) - float(topic_row.p_learn)) < 1e-9, state.p_learn
        assert state.n_obs == 2, "refreshing parameters must not touch how much evidence they have"

    # A second pass over the same data must not accumulate rows: identity is
    # (scope, topic), so re-fitting overwrites rather than multiplies.
    services.ai1.train_params(min_learners=3, min_sequences_per_topic=2)
    with services.scope() as s:
        rows = s.query(BktParams).all()
        keys = [(r.scope, r.topic_id) for r in rows]
    assert len(keys) == len(set(keys)), keys
