"""Consistency between the model the app *fits* and the model the app *runs*.

An estimator that describes a different process than the runtime filter does not
fail loudly. It returns plausible numbers, wrong in a consistent direction, and
those numbers are then handed to ``information_gain`` (which chooses the next
question) and to ``p_correct`` (which tells a learner what they are likely to
remember). Two implementations that are supposed to be one model are the most
expensive kind of bug this codebase can have, so the first half of this file pins
them to each other:

* the EM forward pass must compute the same log-probability the live ``update()``
  chain assigns to the same sequence -- one number, two code paths;
* fitting the rule the app actually runs must recover the parameters that
  generated the data, and fitting the *textbook* rule to the same data must not
  (the measured size of that mistake is asserted, not described);
* a band must be computed from the learner's own evidence on the topic, because
  the alternative -- reading the cohort's sequence count as if it were theirs --
  labels a topic nobody has been asked about yet as a gap.

The rest covers three selection bugs with the same shape: a silent difference
between what the caller asked for and what they got (a session shorter than the
count, a plan that changes on restart, an ordering rule that could never match
its own keys).
"""

