def test_a_topic_the_learner_has_never_been_asked_about_is_not_a_gap():
    """The cohort's sequence count is not this learner's evidence.

    ``train_params`` stores ``n_sequences`` on the params row, and ``band`` used
    to read that as "how many observations this learner has". After one cohort fit
    every untouched topic therefore read ``gapped`` -- the README's cold-start
    promise ("a cold start prints ``new``, never ``low-ability``") held only for a
    deployment where nobody had ever answered anything.
    """
    from adapt.learning.bkt import MIN_OBSERVATIONS_FOR_GAP, BKTParams

    cohort = BKTParams(n_observations=4000)
    assert cohort.band(0.2, observations=0) == "new"
    assert cohort.band(0.2, observations=1) == "new", "one answer is not a finding"
    assert cohort.band(0.2, observations=MIN_OBSERVATIONS_FOR_GAP) == "gapped"
    # The default still reads the params object, so callers with nothing better to
    # hand keep the old behaviour -- `ai1` is not one of them.
    assert cohort.band(0.2) == "gapped"


def test_the_first_wrong_answer_on_a_new_topic_is_not_reported_as_a_gap(client, learner):
    """End to end, through the route a learner's browser calls."""
    headers = learner["headers"]
    item = client.get("/api/v1/practice?count=1", headers=headers).json()["items"][0]["item"]
    topic_id = client.get("/api/v1/practice?count=1", headers=headers).json()["items"][0]["topic_id"]
    session = client.post("/api/v1/sessions", json={"mode": "practice"}, headers=headers).json()["session_id"]

    # An unanswerable value: the point is the band after one scored failure, not
    # the grading path (which test_api_learner_loop walks in full).
    submitted = client.post(
        "/api/v1/attempts",
        json={"session_id": session, "item_id": item["id"], "answer": "\x00definitely-not-an-answer"},
        headers=headers,
    )
    assert submitted.status_code == 200, submitted.text

    traces = {t["topic_id"]: t for t in client.get("/api/v1/profile", headers=headers).json()["mastery"]}
    assert traces, "the attempt has to produce a trace"
    trace = traces.get(topic_id) or list(traces.values())[0]
    assert trace["observations"] == 1
    assert trace["band"] != "gapped", (
        "one wrong answer on a topic that was never taught is an absence of evidence; "
        f"the profile said {trace['band']!r}"
    )


