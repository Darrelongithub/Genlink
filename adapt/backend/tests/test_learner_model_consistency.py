def _diagnostic_probe_script() -> str:
    return """
import json, sys
sys.path.insert(0, sys.argv[1])
from adapt.assessment.selector import diagnostic_plan
topics = [{"id": f"top{i}", "code": f"T{i}", "title": f"T{i}", "difficulty": 0.3 + 0.05 * i} for i in range(8)]
items = {
    f"top{i}": [
        {"id": f"itm{i}_{j}", "topic_id": f"top{i}", "experience_mode": "read",
         "difficulty": 0.4, "active": True, "kind": "numeric"}
        for j in range(6)
    ]
    for i in range(8)
}
plan = diagnostic_plan(topics=topics, items_by_topic=items, count=8, seed="diagnostic")
print(json.dumps([p.item["id"] for p in plan]))
"""


def test_the_diagnostic_is_the_same_plan_in_another_process(tmp_path):
    """``hash()`` on a string is salted per process, so the plan was not.

    The docstring promised "randomised per learner, reproducible for the same
    learner"; two restarts of the same server produced two different diagnostics
    for the same learner, and ``next_items`` seeded the same way.
    """
    script = tmp_path / "probe.py"
    script.write_text(_diagnostic_probe_script())
    env = {**os.environ, "PYTHONPATH": str(SRC)}

    plans = []
    for hash_seed in ("1", "2", "3"):
        out = subprocess.run(
            [sys.executable, str(script), str(SRC)],
            capture_output=True,
            text=True,
            check=True,
            env={**env, "PYTHONHASHSEED": hash_seed},
            cwd=str(REPO_ROOT),
        )
        plans.append(json.loads(out.stdout.strip()))
    assert len(set(map(json.dumps, plans))) == 1, plans


def test_asking_an_interleaved_session_for_eleven_questions_returns_eleven():
    """Approving "interleaving" used to shorten the session instead of mixing it."""
    from adapt.assessment.selector import next_items

    items = {
        "T0": [
            {
                "id": f"i{j}",
                "topic_id": "T0",
                "kind": "numeric",
                "difficulty": 0.4 + j * 0.05,
                "active": True,
                # An item the build cannot mark is not served at all now
                # (selector.gradeable), so a fixture without a key would test nothing.
                "answer_spec": {"value": j + 1},
            }
            for j in range(12)
        ]
    }
    picks = next_items(
        items_by_topic=items,
        mastery={"T0": 0.4},
        count=11,
        directives=[{"strategy": "interleaving", "payload": {"ratio": 0.4}}],
    )
    assert len(picks) == 11


def test_the_diagnostic_prefers_the_easier_topic_when_the_id_and_the_code_differ():
    """The ordering rule compared ``code`` against a pool keyed by ``id``.

    Unless a topic's code happened to equal its id, the lookup matched nothing,
    every topic scored the 0.5 fallback, and "easiest topic first, one item per
    topic" silently became "whatever order the query returned".
    """
    from adapt.assessment.selector import diagnostic_plan

    topics = [
        {"id": "top_hard", "code": "HARD", "title": "Hard", "difficulty": 0.95},
        {"id": "top_easy", "code": "EASY", "title": "Easy", "difficulty": 0.05},
    ]
    items = {
        "top_hard": [{"id": "h0", "topic_id": "top_hard", "experience_mode": "read", "difficulty": 0.9, "active": True}],
        "top_easy": [{"id": "e0", "topic_id": "top_easy", "experience_mode": "read", "difficulty": 0.1, "active": True}],
    }
    plan = diagnostic_plan(topics=topics, items_by_topic=items, count=2, seed="ordering")
    assert [p.item["id"] for p in plan] == ["e0", "h0"]


