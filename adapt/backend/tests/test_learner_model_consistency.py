def test_expected_success_is_the_models_own_prediction():
    """At difficulty 0.5 the target must be BKT's answer, not a second guess.

    The old formula (``p_know * (1 - 0.45*difficulty) + 0.05``) ignored guess and
    slip: it reported 5% success where the trace knows a non-knower still has a
    ``p_guess`` chance. Two different numbers for one question means the selector
    was fitting a target the model does not believe.
    """
    from adapt.assessment.selector import expected_success_rate
    from adapt.learning.bkt import BKTParams

    params = BKTParams(p_guess=0.2, p_slip=0.1)
    for p_know in (0.05, 0.2, 0.5, 0.8, 0.95):
        assert expected_success_rate(p_know, 0.5, params) == pytest.approx(params.p_correct(p_know))

    # Harder items predict less, softer items predict more, and the result is a
    # probability no matter what the author wrote into `difficulty`.
    at_mid = expected_success_rate(0.6, 0.5, params)
    assert expected_success_rate(0.6, 0.9, params) < at_mid < expected_success_rate(0.6, 0.1, params)
    for difficulty in (-3.0, 0.0, 1.0, 4.0):
        assert 0.0 < expected_success_rate(0.6, difficulty, params) < 1.0

    # A wild p_know (a corrupted row) must not raise or return a nan.
    assert 0.0 < expected_success_rate(1e9, 0.5, params) < 1.0
    assert 0.0 < expected_success_rate(-1e9, 0.5, params) < 1.0


